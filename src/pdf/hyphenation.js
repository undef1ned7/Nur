/**
 * Перенос длинных «неразрывных» слов в PDF.
 *
 * @react-pdf/renderer по умолчанию переносит текст только по пробелам
 * (см. defaultHyphenate в @react-pdf/textkit). Поэтому название товара без
 * пробелов — «Кабель-ВВГнг-LS-3х2.5ГОСТ», длинный артикул и т.п. — не
 * спускается на следующую строку, а вылезает за границу колонки таблицы.
 *
 * Колбэк ниже отдаёт движку точки переноса внутри слишком длинных слов:
 * сначала по «естественным» разделителям (дефис, слэш, точка…), а если их нет —
 * кусками фиксированной длины. Короткие слова не трогаем, чтобы обычный текст
 * (описания, комментарии) переносился как раньше — по пробелам.
 */

/** Слова короче этого не режем: они и так помещаются в колонку. */
const MIN_WORD_LENGTH = 18;

/** Максимальная длина куска, на которые режется длинное слово. */
const MAX_CHUNK_LENGTH = 8;

/** Символы, после которых перенос выглядит естественно. */
const SEPARATORS = /[-–—/\\|_.,;:+*×()[\]{}«»"']/;

/**
 * Разбивает слово на части — точки возможного переноса.
 * Склеенные обратно части дают исходное слово (движок этого требует).
 *
 * @param {string} word слово (без пробелов)
 * @returns {string[]} части слова
 */
export function hyphenateLongWord(word) {
  if (!word || word.length <= MIN_WORD_LENGTH) return [word];

  const parts = [];
  let chunk = "";

  for (const char of word) {
    chunk += char;
    if (SEPARATORS.test(char) || chunk.length >= MAX_CHUNK_LENGTH) {
      parts.push(chunk);
      chunk = "";
    }
  }
  if (chunk) parts.push(chunk);

  return parts;
}

export default hyphenateLongWord;
